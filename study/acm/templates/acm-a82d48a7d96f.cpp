/*
对象的初始化和清理
* 生活中我们买电子产品基本都会有初始化设置，在某一天不用的时候也会删除一些自己信息数据保证安全
* C++中的面相对象来源于生活，每个对象都会有初始设置和 对象销毁前的清理数据的设置

一个对象或者变量没有初始状态
或者没有使用完清理，那么会有安全的问题

c++利用了构造函数和析构函数解决
注：如果我们不提供构造函数和析构函数，那么编译器会提供
    但是编译器提供的是空实现的

构造函数语法： 类名(){}
    1、构造函数，没有返回值也不写void
    2、函数名称与类名相同
    3、构造函数可以有参数，因此可以发生重载
    4、程序在调用对象时候会自动调用，无需手动操作，而且只会调用一次

析构函数语法： ~类名(){}
    1、构造函数，没有返回值也不写void
    2、函数名与类名相同，在名称前加上~
    3、析构函数不可以有参数，所以不可以发生重载
    4、程序在对象销毁前会自动调用析构，无需手动操作，而且只会调用一次
*/
#include<bits/stdc++.h>
using namespace std;

//1、构造函数
class Person
{
public:
    Person()
    {
        cout<< 1 << endl;
    }
    ~Person()
    {
        cout << 2 << endl;
    }
};

void text1()
{
    Person p; //在栈上的数据，text1执行完毕就会释放这个对象
}
int main()
{
    text1();
    Person p1;//只有构造没有析构

    system("pause");//因为有这个，程序中断，但是还没结束main函数，所以还没有析构，去掉就有了
    return 0;
}